"""Writes supabase/migrations/0005_sync_hardening.sql from notecad_brain/sync.py, so the cloud journal, its capture
function and its triggers are the ones the brain installs on Postgres. tests/test_phase6.py fails when they differ.

    .venv\\Scripts\\python.exe tools\\gen_sync_migration.py           # write the file
    .venv\\Scripts\\python.exe tools\\gen_sync_migration.py --check   # exit 1 if the file is out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
OUT = HERE.parents[3] / "supabase" / "migrations" / "0005_sync_hardening.sql"

from notecad_brain.sync import PG_FUNCTION, pg_triggers  # noqa: E402

HEADER = """-- Ionity NoteCad | Ionity Global (Pty) Ltd | AEDI
-- Author: Dennis Grobler (Wabakipi) <dennis.g@ionity.digital>
-- Policy 986 AED | License AED 900 | (c) 2026 Ionity Global (Pty) Ltd - All rights reserved
-- Phase 6 (ADR 0013): sync hardening. Generated by services/brain/tools/gen_sync_migration.py from
-- notecad_brain/sync.py; do not edit by hand.
--  * nc_sync_capture() runs as security definer, so an app writing through PostgREST under row-level security can
--    still journal its change (the journal tables have row-level security on and no policies).
--  * the workspace lookup for tables without workspace_id is generated from sync.TABLES.
--  * sync_rejects keeps a change that could not be applied instead of blocking the whole batch.
--  * sync_state.epoch names this journal, so a worker notices a hub that was wiped and starts again.
"""


def render() -> str:
    parts = [HEADER,
             "create table if not exists sync_rejects (\n"
             "  id bigserial primary key, tbl text not null, pk text not null, origin text not null, origin_seq bigint,\n"
             "  ts text, error text not null, change text not null, at text not null);",
             "alter table sync_rejects enable row level security;",
             "insert into sync_state(key, value) values ('epoch', md5(random()::text || clock_timestamp()::text))\n"
             "  on conflict (key) do nothing;",
             "",
             PG_FUNCTION.strip() + ";",
             ""]
    parts += [s + ";" for s in pg_triggers()]
    return "\n".join(parts) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else f"{OUT.name} differs from notecad_brain/sync.py: run this tool")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
