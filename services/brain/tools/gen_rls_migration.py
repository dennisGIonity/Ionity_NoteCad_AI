"""Writes supabase/migrations/0007_roles_seats_permissions.sql (ADR 0014) from the brain itself:

  1  the schema: migration 7 in notecad_brain/db.py, the same statements the brain runs on SQLite and Postgres
  2  the journal: sync.py's new columns, nc_sync_annotate() and capture triggers for the tables 0005 did not have
  3  row-level security: permissions.py's helpers, the last-owner guard, two views and one policy per table and
     command, rendered from its permission matrix

    .venv\\Scripts\\python.exe tools\\gen_rls_migration.py           # write the file
    .venv\\Scripts\\python.exe tools\\gen_rls_migration.py --check   # exit 1 if the file is out of date (CI runs this)
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
OUT = HERE.parents[3] / "supabase" / "migrations" / "0007_roles_seats_permissions.sql"

from notecad_brain.db import MIGRATIONS  # noqa: E402
from notecad_brain.permissions import rls_statements  # noqa: E402
from notecad_brain.sync import PHASE6_TABLES, TABLES, pg_journal_upgrade, pg_triggers  # noqa: E402

VERSION = 7
HEADER = """-- Ionity NoteCad | Ionity Global (Pty) Ltd | AEDI
-- Author: Dennis Grobler (Wabakipi) <dennis.g@ionity.digital>
-- Policy 986 AED | License AED 900 | (c) 2026 Ionity Global (Pty) Ltd - All rights reserved
-- 0007 (ADR 0014): roles, seats and permission-aware sync. Generated by services/brain/tools/gen_rls_migration.py from
-- notecad_brain/db.py (migration 7), notecad_brain/sync.py and notecad_brain/permissions.py; do not edit by hand.
-- It can run again: the schema statements are written to, and the rest replaces itself.
"""


def new_tables() -> list[str]:
    """Synced tables 0005 has no capture trigger for."""
    return [t for t in TABLES if t not in PHASE6_TABLES]


def render() -> str:
    statements = next(s for v, _, s in MIGRATIONS if v == VERSION)
    parts = [HEADER, "-- 1. schema (db.MIGRATIONS[7])"]
    parts += [s + ";" for s in statements]
    parts += ["", "-- 2. the journal (sync.py): who made a change, its node, how visible it was, the version it edited"]
    parts += [s + ";" for s in pg_journal_upgrade()]
    parts += [s + ";" for s in pg_triggers(new_tables())]
    parts += ["", "-- 3. row-level security (permissions.py)"]
    parts += [s + ";" for s in rls_statements()]
    return "\n".join(parts) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else f"{OUT.name} differs from db.py / sync.py / permissions.py: run this tool")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
