"""Writes the newest Supabase migration of ADR 0014 from the brain itself, and checks the ones that have shipped.

  0007_roles_seats_permissions.sql  shipped: must stay as it was (checked by its hash). It holds migration 7's schema,
                                    the journal additions of sync.py and the first row-level security
  0008_device_lookups_inbox_rls.sql written here: migration 8 (notecad_brain/db.py) and the row-level security of
                                    permissions.py as it is now (rls_statements: helpers, the last-owner guard, two
                                    views and one policy per table and command, rendered from the permission matrix)

When the matrix or a policy changes after 0008 has shipped: freeze 0008 below and point LATEST at the next number.

    .venv\\Scripts\\python.exe tools\\gen_rls_migration.py           # write the newest file
    .venv\\Scripts\\python.exe tools\\gen_rls_migration.py --check   # exit 1 if a file is out of date (CI runs this)
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
DIR = HERE.parents[3] / "supabase" / "migrations"

from notecad_brain.db import MIGRATIONS  # noqa: E402
from notecad_brain.permissions import rls_statements  # noqa: E402
from notecad_brain.sync import PHASE6_TABLES, TABLES  # noqa: E402

VERSION = 8
OUT = DIR / "0008_device_lookups_inbox_rls.sql"
# shipped files and the SHA-256 of their text with LF line ends (a Windows checkout may give them CRLF)
FROZEN = {"0007_roles_seats_permissions.sql": "6393bd9b80d1c28f516a7a83087fe0fb473aca7d673c1be771005a60283d4885"}
HEADER = """-- Ionity NoteCad | Ionity Global (Pty) Ltd | AEDI
-- Author: Dennis Grobler (Wabakipi) <dennis.g@ionity.digital>
-- Policy 986 AED | License AED 900 | (c) 2026 Ionity Global (Pty) Ltd - All rights reserved
-- 0008 (ADR 0014, step 4): lookups for joining, the device copy and Inbox routing, and the row-level security of
-- notecad_brain/permissions.py as it is now (an Inbox item with no recipients is the owners' alone). Generated by
-- services/brain/tools/gen_rls_migration.py; do not edit by hand. It can run again: everything replaces itself.
"""


def new_tables() -> list[str]:
    """Synced tables 0005 has no capture trigger for (0007 added theirs)."""
    return [t for t in TABLES if t not in PHASE6_TABLES]


def render() -> str:
    statements = next(s for v, _, s in MIGRATIONS if v == VERSION)
    parts = [HEADER, f"-- 1. schema (db.MIGRATIONS[{VERSION}])"]
    parts += [s + ";" for s in statements]
    parts += ["", "-- 2. row-level security (permissions.py)"]
    parts += [s + ";" for s in rls_statements()]
    return "\n".join(parts) + "\n"


def frozen_ok() -> list[str]:
    """The shipped files that changed (none, normally)."""
    bad = []
    for name, want in FROZEN.items():
        f = DIR / name
        text = f.read_text(encoding="utf-8") if f.exists() else ""
        if hashlib.sha256(text.replace("\r\n", "\n").encode("utf-8")).hexdigest() != want:
            bad.append(name)
    return bad


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        bad = frozen_ok()
        ok = not bad and OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("up to date" if ok else
              f"shipped migrations changed: {', '.join(bad)}" if bad else
              f"{OUT.name} differs from db.py / permissions.py: run this tool")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
